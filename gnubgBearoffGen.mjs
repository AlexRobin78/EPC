export const memo = new Map();
export const clearMemo = () => memo.clear();

// ---- gnubg's HeuristicBearoff (used only to cross-check this port against the real C engine)
function heuristicMove(b0, d0, d1) {
    const bd = b0.slice();
    const dice = d0 === d1 ? [d0, d0, d0, d0] : [d0, d1];
    const c = dice.length;
    for (let i = 0; i < c; i++) {
        let nMax;
        for (nMax = 5; nMax > 0; nMax--) if (bd[nMax]) break;
        if (!bd[nMax]) break;
        let n = -1;
        const d = dice[i];
        if (bd[d - 1]) n = d - 1;
        else if (d - 1 > nMax) n = nMax;
        else {
            let nTotal = d - 1;
            for (let j = i + 1; j < c; j++) {
                nTotal += dice[j];
                if (nTotal < 6 && bd[nTotal]) { n = nTotal; break; }
            }
            if (n < 0) {
                for (let s = d; s <= nMax; s++) {
                    if (bd[s] >= 2 && !bd[s - d] && (n === -1 || bd[s] > bd[n])) n = s;
                }
            }
            if (n < 0) {
                for (let s = d; s <= nMax; s++) {
                    if (n === -1 || bd[s] > bd[n] || (bd[s] === bd[n] && bd[s - d] < bd[n - d])) n = s;
                }
            }
        }
        bd[n]--;
        if (n >= d) bd[n - d]++;
    }
    return bd;
}

export function distHeuristic(b) {
    // exact integer arithmetic of gnubg's GenerateBearoff (uint16 probabilities)
    const key = keyOf(b);
    let e = memo.get(key);
    if (e) return e;
    const q = new Int32Array(NB);
    if (total(b) === 0) q[0] = 0xFFFF;
    else {
        const acc = new Int32Array(NB);
        for (let d0 = 1; d0 <= 6; d0++) for (let d1 = 1; d1 <= d0; d1++) {
            const nb = heuristicMove(b, d0, d1);
            const sub = distHeuristic(nb);
            const mult = d0 === d1 ? 1 : 2;
            for (let i = 0; i < 31; i++) acc[i + 1] += sub.q[i] * mult;
        }
        for (let i = 0; i < NB; i++) q[i] = Math.floor((acc[i] + 18) / 36);
    }
    const p = new Float64Array(NB);
    for (let i = 0; i < NB; i++) p[i] = q[i] / 65535;
    e = finishDist(p);
    e.q = q;
    memo.set(key, e);
    return e;
}

// Exact policy: for every roll play to the position with the smallest expected number of rolls.
export function distExact(b) {
    const key = keyOf(b);
    let e = memo.get(key);
    if (e) return e;
    const p = new Float64Array(NB);
    if (total(b) === 0) p[0] = 1;
    else {
        for (let d0 = 1; d0 <= 6; d0++) for (let d1 = 1; d1 <= d0; d1++) {
            const succ = successors(b, d0, d1);
            let best = null;
            for (const s of succ) {
                const sd = distExact(s);
                if (!best || sd.mean < best.mean - 1e-12) best = sd;
            }
            const w = (d0 === d1 ? 1 : 2) / 36;
            for (let i = 0; i < NB - 1; i++) p[i + 1] += w * best.p[i];
        }
    }
    e = finishDist(p);
    memo.set(key, e);
    return e;
}

